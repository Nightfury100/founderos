#!/usr/bin/env node
/**
 * Bundles the active dataset into an importable module for the Cloudflare
 * Worker (Workers have no filesystem). Picks the real dataset when it exists,
 * otherwise the clearly-labelled fixture. Run automatically by `npm run deploy`.
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const DATA = path.join(here, "..", "data");

const readJson = async (p) => {
  try { return JSON.parse(await readFile(p, "utf8")); } catch { return null; }
};

const real = await readJson(path.join(DATA, "products.json"));
const realIndex = await readJson(path.join(DATA, "manuals-index.json"));
const parts = await readJson(path.join(DATA, "parts.json"));
const sources = await readJson(path.join(DATA, "sources.json"));

let dataset;
if (real?.products?.length) {
  dataset = {
    mode: "real",
    version: real.version,
    products: real.products,
    passages: realIndex?.passages ?? [],
    parts: parts?.parts ?? null,
    sourcesCount: sources?.manifest?.length ?? 0,
  };
} else {
  const fx = await readJson(path.join(DATA, "fixtures", "products.fixture.json"));
  const fxIdx = await readJson(path.join(DATA, "fixtures", "manuals-index.fixture.json"));
  dataset = {
    mode: "fixture",
    version: fx.version,
    notice: fx.notice,
    products: fx.products,
    passages: fxIdx?.passages ?? [],
    parts: null,
    sourcesCount: 0,
  };
}

const out = path.join(here, "dataset.generated.mjs");
await writeFile(
  out,
  `// GENERATED by worker/build-dataset.mjs - do not edit. Re-run npm run bundle-data after acquisition.\n` +
    `export default ${JSON.stringify(dataset, null, 2)};\n`
);
console.log(`Wrote ${out} (mode: ${dataset.mode}, ${dataset.products.length} products, ${dataset.passages.length} passages).`);
